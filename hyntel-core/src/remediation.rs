use anyhow::Result;
use std::path::Path;
use crate::models::{CheckResult, Platform};

pub fn remediation_filename(platform: &Platform) -> &'static str {
    match platform {
        Platform::Linux => "remediate_linux.sh",
        Platform::MacOS => "remediate_macos.sh",
        Platform::Windows => "remediate_windows.ps1",
        Platform::Unknown => "remediate_unknown.txt",
    }
}

pub fn render_remediation_script(platform: &Platform, failed_results: &[CheckResult]) -> String {
    match platform {
        Platform::Windows => render_powershell_remediation(failed_results),
        _ => render_bash_remediation(failed_results),
    }
}

fn render_bash_remediation(failed_results: &[CheckResult]) -> String {
    let mut lines = vec![
        "#!/usr/bin/env bash".to_string(),
        "set -euo pipefail".to_string(),
        "".to_string(),
        "# Generated by hyntel. Review before execution.".to_string(),
        "# Run with: sudo bash remediate_*.sh".to_string(),
        "".to_string(),
    ];

    for result in failed_results {
        lines.push("".to_string());
        lines.push(format!("# {}", result.rule_id));
        for action in &result.remediation {
            lines.push(action.clone());
        }
    }

    lines.push("".to_string());
    lines.join("\n") + "\n"
}

fn render_powershell_remediation(failed_results: &[CheckResult]) -> String {
    let mut lines = vec![
        "$ErrorActionPreference = 'Stop'".to_string(),
        "".to_string(),
        "# Generated by hyntel. Review before execution.".to_string(),
        "# Run with: PowerShell -ExecutionPolicy Bypass -File remediate_windows.ps1".to_string(),
        "".to_string(),
    ];

    for result in failed_results {
        lines.push("".to_string());
        lines.push(format!("# {}", result.rule_id));
        for action in &result.remediation {
            lines.push(action.clone());
        }
    }

    lines.push("".to_string());
    lines.join("\n") + "\n"
}

pub fn write_remediation_script(output_dir: &Path, platform: &Platform, failed_results: &[CheckResult]) -> Result<std::path::PathBuf> {
    std::fs::create_dir_all(output_dir)?;
    let filename = remediation_filename(platform);
    let path = output_dir.join(filename);
    let content = render_remediation_script(platform, failed_results);
    std::fs::write(&path, content)?;

    #[cfg(not(target_os = "windows"))]
    if !matches!(platform, Platform::Windows) {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&path)?.permissions();
        perms.set_mode(0o750);
        std::fs::set_permissions(&path, perms)?;
    }

    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{CheckResult, CheckStatus, Platform};

    #[test]
    fn test_render_bash_remediation() {
        let results = vec![
            CheckResult {
                rule_id: "test_rule".to_string(),
                status: CheckStatus::Fail,
                details: "Test".to_string(),
                observed_value: None,
                remediation: vec!["echo 'fix 1'".to_string(), "echo 'fix 2'".to_string()],
                related_cves: vec![],
            },
        ];
        let script = render_bash_remediation(&results);
        assert!(script.contains("#!/usr/bin/env bash"));
        assert!(script.contains("set -euo pipefail"));
        assert!(script.contains("# test_rule"));
        assert!(script.contains("echo 'fix 1'"));
        assert!(script.contains("echo 'fix 2'"));
    }

    #[test]
    fn test_render_powershell_remediation() {
        let results = vec![
            CheckResult {
                rule_id: "test_rule".to_string(),
                status: CheckStatus::Fail,
                details: "Test".to_string(),
                observed_value: None,
                remediation: vec!["Write-Host 'fix 1'".to_string()],
                related_cves: vec![],
            },
        ];
        let script = render_powershell_remediation(&results);
        assert!(script.contains("$ErrorActionPreference = 'Stop'"));
        assert!(script.contains("# test_rule"));
        assert!(script.contains("Write-Host 'fix 1'"));
    }

    #[test]
    fn test_remediation_filename() {
        assert_eq!(remediation_filename(&Platform::Linux), "remediate_linux.sh");
        assert_eq!(remediation_filename(&Platform::MacOS), "remediate_macos.sh");
        assert_eq!(remediation_filename(&Platform::Windows), "remediate_windows.ps1");
    }
}